#!/usr/bin/env bash
# Write app/Brand.xcconfig from config/brand.env.
# A shipping bundle id left as {{BUNDLE_ID}} becomes a debug-only temporary
# identifier. That temporary id is never written to config/release.env.
set -euo pipefail
# shellcheck source=lib.sh
source "$(dirname "$0")/lib.sh"
root="$(strip_root)"
strip_load_brand

bundle="${BUNDLE_ID:-}"
if strip_is_unset "$bundle"; then
  bundle="local.preview.strip"
fi

support="${SUPPORT_EMAIL:-}"
website="${WEBSITE:-${WEBSITE_URL:-}}"
if strip_is_unset "$support"; then
  support=""
fi
if strip_is_unset "$website"; then
  website=""
fi

# xcconfig treats // as a comment. Keep URLs and base64 intact.
xc_escape() {
  local value="$1"
  value=${value//\/\//\$(SLASH)\$(SLASH)}
  printf '%s' "$value"
}

emit() {
  local setting="$1"
  local name="$2"
  local value="${3:-}"
  if strip_is_unset "$value"; then
    echo "MISSING: {{${name}}}" >&2
    value=""
  fi
  printf '%s = %s\n' "$setting" "$(xc_escape "$value")"
}

mkdir -p "$root/app"
{
  echo "// Generated by scripts/gen-brand.sh from config/brand.env. Do not edit."
  echo "SLASH = /"
  echo "STRIP_APP_NAME = $(xc_escape "${APP_NAME}")"
  echo "STRIP_URL_SCHEME = $(xc_escape "${URL_SCHEME}")"
  echo "STRIP_BUNDLE_ID = $(xc_escape "${bundle}")"
  emit STRIP_SUPPORT_EMAIL SUPPORT_EMAIL "${support}"
  emit STRIP_WEBSITE WEBSITE_URL "${website}"
  emit STRIP_APPCAST_URL APPCAST_URL "${APPCAST_URL:-}"
  emit STRIP_SPARKLE_PUBLIC_ED_KEY SPARKLE_PUBLIC_ED_KEY "${SPARKLE_PUBLIC_ED_KEY:-}"
  emit STRIP_TRIAL_DAYS TRIAL_DAYS "${TRIAL_DAYS:-}"
  emit STRIP_DODO_ENV DODO_ENV "${DODO_ENV:-}"
  emit STRIP_DODO_PRODUCT_ID_1 DODO_PRODUCT_ID_1 "${DODO_PRODUCT_ID_1:-}"
  emit STRIP_DODO_PRODUCT_ID_3 DODO_PRODUCT_ID_3 "${DODO_PRODUCT_ID_3:-}"
  emit STRIP_DODO_PRODUCT_ID_5 DODO_PRODUCT_ID_5 "${DODO_PRODUCT_ID_5:-}"
  emit STRIP_DODO_PRODUCT_ID_20 DODO_PRODUCT_ID_20 "${DODO_PRODUCT_ID_20:-}"
  emit STRIP_DODO_CHECKOUT_URL DODO_CHECKOUT_URL "${DODO_CHECKOUT_URL:-}"
} > "$root/app/Brand.xcconfig"
