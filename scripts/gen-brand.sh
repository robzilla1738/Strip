#!/usr/bin/env bash
# Write app/Brand.xcconfig from config/brand.env.
# A shipping bundle id left as {{BUNDLE_ID}} becomes a debug-only temporary
# identifier. That temporary id is never written to config/release.env.
set -euo pipefail
# shellcheck source=lib.sh
source "$(dirname "$0")/lib.sh"
root="$(strip_root)"
strip_load_brand

bundle="${BUNDLE_ID:-}"
if strip_is_unset "$bundle"; then
  bundle="local.preview.strip"
fi

support="${SUPPORT_EMAIL:-}"
website="${WEBSITE:-${WEBSITE_URL:-}}"
if strip_is_unset "$support"; then
  support=""
fi
if strip_is_unset "$website"; then
  website=""
fi

mkdir -p "$root/app"
cat > "$root/app/Brand.xcconfig" <<EOF
// Generated by scripts/gen-brand.sh from config/brand.env. Do not edit.
STRIP_APP_NAME = ${APP_NAME}
STRIP_URL_SCHEME = ${URL_SCHEME}
STRIP_BUNDLE_ID = ${bundle}
STRIP_SUPPORT_EMAIL = ${support}
STRIP_WEBSITE = ${website}
EOF
