#!/usr/bin/env bash
# Write config/release.env and key files from CI secrets. Values are not printed.
# A missing secret is left unset so release.sh can print MISSING: {{NAME}}.
set -euo pipefail
# shellcheck source=lib.sh
source "$(dirname "$0")/lib.sh"
root="$(strip_root)"
mkdir -p "$root/build" "$root/config"

if ! strip_is_unset "${ASC_KEY_P8:-}"; then
  printf '%s\n' "$ASC_KEY_P8" >"$root/build/AuthKey.p8"
  export ASC_KEY_P8_PATH="$root/build/AuthKey.p8"
fi
if ! strip_is_unset "${SPARKLE_PRIVATE_KEY:-}"; then
  printf '%s\n' "$SPARKLE_PRIVATE_KEY" >"$root/build/sparkle_private.pem"
  export SPARKLE_PRIVATE_KEY_PATH="$root/build/sparkle_private.pem"
fi

keys=(
  APPLE_TEAM_ID
  DEVELOPER_ID_APPLICATION
  BUNDLE_ID
  ASC_KEY_ID
  ASC_ISSUER_ID
  ASC_KEY_P8_PATH
  NOTARY_PROFILE
  SPARKLE_PUBLIC_ED_KEY
  SPARKLE_PRIVATE_KEY_PATH
  APPCAST_URL
  UPDATE_HOST_UPLOAD
  DODO_ENV
  DODO_PRODUCT_ID_1
  DODO_PRODUCT_ID_3
  DODO_PRODUCT_ID_5
  DODO_PRODUCT_ID_20
  DODO_CHECKOUT_URL
  TRIAL_DAYS
  SUPPORT_EMAIL
  WEBSITE_URL
)
{
  echo "# Generated by scripts/write-ci-env.sh. Do not commit."
  for name in "${keys[@]}"; do
    value="${!name-}"
    if strip_is_unset "$value"; then
      continue
    fi
    printf '%s=%q\n' "$name" "$value"
  done
} >"$root/config/release.env"
echo "wrote config/release.env"
